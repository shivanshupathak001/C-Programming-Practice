// WAP to check if a given number is natural or not
#include<stdio.h>
int main() {
    int num;
    printf("Enter a Number \n");
    scanf("%d",&num);
    if(num>=1) {
        printf("Natural Number \n");
    }
    else {
        printf("Not a Natural Number \n");
    }
    return 0;
} 