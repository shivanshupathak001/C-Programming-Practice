//WAP to understand the arithmetic instructions , relational operator and logical operator 
#include<stdio.h>
int main(){
    printf("%d\n",7%4);
    printf("%d\n",-7%4);
    printf("%d\n",5==5);
    printf("%d\n",7>8);
    printf("%d\n",2!=2);
    printf("%d\n",4>3 && 4>5);
    printf("%d\n",4>3 || 4>5);
    return 0;
}